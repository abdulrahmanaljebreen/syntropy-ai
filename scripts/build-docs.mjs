#!/usr/bin/env node
// Builds readable guides from the Figma doc pages:
//   knowledge/components/<page>.md   one per component page (manifest tables + doc page)
//   knowledge/foundations/figma/<page>.md and knowledge/guides/<page>.md
// Uses the page cache written by sync-figma.mjs; fetches guide pages if missing.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { getJSON, DS_FILE } from './lib/figma.mjs';
import { docToMarkdown } from './lib/docs.mjs';
import { cleanText } from './lib/tokens.mjs';

const index = JSON.parse(await readFile('knowledge/components/index.json', 'utf8'));
const examples = existsSync('knowledge/examples/components/index.json')
  ? JSON.parse(await readFile('knowledge/examples/components/index.json', 'utf8')) : [];
const descriptions = existsSync('knowledge/components/descriptions.json')
  ? JSON.parse(await readFile('knowledge/components/descriptions.json', 'utf8')) : {};

const figmaLink = (id) => `https://www.figma.com/design/${DS_FILE}?node-id=${id.replace(':', '-')}`;
const HEADER = [
  '<!-- Generated by scripts/build-docs.mjs from the Syntropy Figma file. Edit in Figma, not here. -->',
  '<!-- syntropy-lint-disable: text mirrors Figma; conflicts are tracked in docs/reviews -->',
  '',
  '> Agent note: this guide mirrors the Figma doc page. Where it conflicts with the Syntropy rules (Western digits, currency after the amount, direction never a code parameter, semantic tokens only), the rules win.',
].join('\n');
const DOC_FRAME = /\bdoc(umentation)?\b|· documentation|documentation/i;
// Private pages are never mentioned in generated knowledge. Their names are not in this
// public repo: they come from SYNTROPY_PRIVATE_NAMES (comma-separated; a GitHub secret in CI)
// or ~/.config/syntropy/private-names. Without them the build stops rather than leak.
function privateNames() {
  const file = join(homedir(), '.config', 'syntropy', 'private-names');
  const raw = process.env.SYNTROPY_PRIVATE_NAMES || (existsSync(file) ? readFileSync(file, 'utf8') : '');
  return raw.split(/[,\n]/).map((x) => x.trim()).filter(Boolean);
}
const esc = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
export function redact(md, names = privateNames()) {
  if (!names.length) throw new Error('Set SYNTROPY_PRIVATE_NAMES (or ~/.config/syntropy/private-names) before building the guides.');
  const alt = names.map(esc).join('|');
  const phrase = new RegExp(`,?\\s*(on|in) the (\\p{Extended_Pictographic}\\s*)?(${alt}) page`, 'giu');
  const word = new RegExp(`\\b(${alt})\\b|69:977`, 'u');
  return md
    .split('\n')
    .map((l) => l.replace(phrase, ''))
    .filter((l) => !word.test(l))
    .join('\n');
}
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

async function pageNode(id) {
  const cache = `.cache/figma/page-${id.replace(/:/g, '_')}.json`;
  const res = existsSync(cache)
    ? JSON.parse(await readFile(cache, 'utf8'))
    : await getJSON(`files/${DS_FILE}/nodes?ids=${encodeURIComponent(id)}`, { cacheKey: `page-${id}` });
  return res.nodes[id]?.document;
}

function docFrames(page) {
  return (page.children || []).filter((f) => f.type === 'FRAME' && DOC_FRAME.test(f.name) && f.visible !== false);
}

function propsTable(c) {
  if (!c.props.length) return '_No properties._\n';
  const rows = c.props.map((p) => `| ${cell(p.name)} | \`${p.canonical}\` | ${p.type.toLowerCase().replace('_', ' ')} | ${cell((p.options || []).join(', ') || (p.defaultComponent ? `default ${p.defaultComponent}` : ''))} | ${cell(p.default)} |`);
  return ['| Property in Figma | Code name | Type | Values | Default |', '| --- | --- | --- | --- | --- |', ...rows].join('\n') + '\n';
}

async function buildComponentPage(p) {
  const comps = index.components.filter((c) => c.page === p.slug && !c.hidden);
  const page = await pageNode(p.id);
  const docs = page ? docFrames(page).map(docToMarkdown) : [];
  const meta = docs[0]?.meta || {};
  const ref = examples.find((e) => e.page === p.slug && e.kind === 'reference' && e.path);
  const out = [HEADER, '', `# ${p.name}`, ''];
  out.push(`Figma: [${p.code}. ${p.name}](${figmaLink(p.id)}) · Family: ${p.family} · Status: ${meta.status || p.status}${meta.version ? ` · Version ${meta.version}` : ''}${meta.updated ? ` · Updated ${meta.updated}` : ''}`, '');
  if (meta.summary) out.push(meta.summary, '');
  if (ref) out.push(`Reference image (every variant, labelled): \`${ref.path}\``, '');

  out.push('## Components on this page', '');
  out.push('| Component | Figma id | Kind | Variants | In library | Example image |', '| --- | --- | --- | --- | --- | --- |');
  for (const c of comps) {
    const img = examples.find((e) => e.id === c.id && e.path)?.path;
    out.push(`| ${cell(c.name)} | [${c.id}](${figmaLink(c.id)}) | ${c.kind} | ${c.variantCount} | ${c.published ? 'yes' : 'no'} | ${img ? `\`${img}\`` : ''} |`);
  }
  out.push('');
  for (const c of comps) {
    const d = descriptions[c.id];
    const desc = (typeof d === 'string' ? d : d?.description) || c.description;
    out.push(`### ${c.name}`, '');
    if (desc) out.push(cleanText(desc), '');
    if (d && typeof d === 'object') {
      if (d.level) out.push(`Level: ${d.level}${d.contains?.length ? ` · Contains: ${d.contains.join(', ')}` : ''}${d.partOf?.length ? ` · Part of: ${d.partOf.join(', ')}` : ''}`, '');
      if (d.useWhen?.length) out.push('Use when:', ...d.useWhen.map((x) => `- ${cleanText(x)}`), '');
      if (d.dontUseWhen?.length) out.push("Don't use when:", ...d.dontUseWhen.map((x) => `- ${cleanText(x)}`), '');
      if (d.a11y) out.push(`Accessibility: ${cleanText(d.a11y)}`, '');
      if (d.compliance) out.push(`Compliance: ${cleanText(d.compliance)}`, '');
    }
    if (!c.published) out.push('> Not published to the Figma library. Use it by name everywhere; in another Figma file take its published route or copy it from the Syntropy file (syntropy-components, unpublished.md).', '');
    out.push(propsTable(c));
  }

  if (docs.length) {
    out.push('## Guide from the doc page', '');
    for (const d of docs) out.push(d.markdown.replace(/^## /gm, '### ').replace(/^### (?=.*\n)/gm, (m) => m), '');
  } else out.push('## Guide from the doc page', '', '_This page has no doc page in Figma yet._', '');

  out.push('## Sources', '', `- Figma page ${p.id}${docs.length ? `, doc frame ${docFrames(page).map((f) => f.id).join(', ')}` : ''}`, `- Manifest: \`knowledge/components/index.json\``, '');
  const md = redact(out.join('\n')).replace(/\n{3,}/g, '\n\n');
  await writeFile(`knowledge/components/${p.slug}.md`, md);
  return { slug: p.slug, docs: docs.length, sections: docs.flatMap((d) => d.sections).length, bytes: md.length };
}

async function buildPlainPage(p, dir) {
  const page = await pageNode(p.id);
  // Foundation and guide pages: every visible top-level frame is documentation.
  const frames = page ? (page.children || []).filter((f) => f.type === 'FRAME' && f.visible !== false) : [];
  const docs = frames.map(docToMarkdown).filter((d) => d.markdown.trim().length > 40);
  const out = [HEADER, '', `# ${p.name}`, '', `Figma: [${p.name}](${figmaLink(p.id)})`, ''];
  if (docs[0]?.meta?.summary) out.push(docs[0].meta.summary, '');
  for (const d of docs) out.push(d.markdown, '');
  if (!docs.length) out.push('_No doc frame found on this page._', '');
  out.push('## Sources', '', `- Figma page ${p.id}`, '');
  await mkdir(dir, { recursive: true });
  await writeFile(`${dir}/${p.slug}.md`, redact(out.join('\n')).replace(/\n{3,}/g, '\n\n'));
  return { slug: p.slug, docs: docs.length };
}

const results = [];
for (const p of index.pages) results.push(await buildComponentPage(p));
for (const p of index.foundations) results.push(await buildPlainPage(p, 'knowledge/foundations/figma'));
for (const p of index.guides) results.push(await buildPlainPage(p, 'knowledge/guides'));

const missing = results.filter((r) => !r.docs).map((r) => r.slug);
console.log({ pages: results.length, withDocs: results.length - missing.length, missing });
