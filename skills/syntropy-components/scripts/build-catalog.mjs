#!/usr/bin/env node
// Builds references/catalog.md: every Syntropy component grouped by family and page,
// with id, level, library status, variant properties, other properties and a one-line description.
// Zero dependencies, node >= 20. Rerun whenever the component index or descriptions change.
//
// Usage:
//   node scripts/build-catalog.mjs                     (auto-detect inputs, write references/catalog.md)
//   node scripts/build-catalog.mjs --index <path> --descriptions <path> --out <path>
//   node scripts/build-catalog.mjs --check             (exit 1 if catalog.md is out of date)
//
// Inputs are looked up in this order:
//   1. the --index / --descriptions flags
//   2. references/data/components-index.json and references/data/components-descriptions.json (inside the skill)
//   3. ../../knowledge/components/index.json and descriptions.json (when the skill sits inside the repo)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const skillRoot = resolve(here, '..');
const repoRoot = resolve(skillRoot, '..', '..');
const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const checkOnly = args.includes('--check');

function firstExisting(paths) {
  for (const p of paths) if (p && existsSync(p)) return p;
  return null;
}

const indexPath = firstExisting([
  flag('--index'),
  join(skillRoot, 'references/data/components-index.json'),
  join(repoRoot, 'knowledge/components/index.json'),
]);
const descPath = firstExisting([
  flag('--descriptions'),
  join(skillRoot, 'references/data/components-descriptions.json'),
  join(repoRoot, 'knowledge/components/descriptions.json'),
]);
const outPath = flag('--out') || join(skillRoot, 'references/catalog.md');

if (!indexPath) {
  console.error('components index not found; pass --index <path>');
  process.exit(1);
}

const index = JSON.parse(await readFile(indexPath, 'utf8'));
const descriptions = descPath ? JSON.parse(await readFile(descPath, 'utf8')) : {};

// Writing rules: no em dash, no table-breaking pipes or newlines.
const clean = (s) =>
  String(s ?? '')
    .replace(/\s*\u2014\s*/g, ': ')
    .replace(/\|/g, '\\|')
    .replace(/\s+/g, ' ')
    .trim();

function oneLine(text) {
  const t = clean(text);
  if (t.length <= 220) return t;
  const m = t.match(/^(.{40,220}?[.!?])\s+(?=[A-Z«(])/);
  return m ? m[1] : t.slice(0, 217) + '...';
}

function variantSummary(props) {
  return props
    .filter((p) => p.type === 'VARIANT')
    .map((p) => {
      const opts = (p.options || []).map(String);
      const shown = opts.length > 12 ? [...opts.slice(0, 8), `... +${opts.length - 8} more`] : opts;
      return `\`${clean(p.name)}\`=${shown.map(clean).join(' / ')}`;
    })
    .join('<br>');
}

const typeTag = { BOOLEAN: 'bool', TEXT: 'text', INSTANCE_SWAP: 'swap' };
function otherProps(props) {
  return props
    .filter((p) => p.type !== 'VARIANT')
    .map((p) => `${clean(p.name)} (${typeTag[p.type] || p.type.toLowerCase()})`)
    .join(', ');
}

function hasReferenceImage(slug) {
  return (
    existsSync(join(skillRoot, 'references/data/examples', slug, 'reference.png')) ||
    existsSync(join(repoRoot, 'knowledge/examples/components', slug, 'reference.png'))
  );
}

const comps = index.components;
const nameCount = comps.reduce((m, c) => m.set(c.name, (m.get(c.name) || 0) + 1), new Map());
const unpublishedSets = comps.filter((c) => c.kind === 'set' && !c.published).length;
const unpublishedStandalone = comps.filter((c) => c.kind === 'component' && !c.published).length;

const L = [];
L.push('<!-- syntropy-lint-disable eastern-arabic-numerals: variant values are copied verbatim from Figma -->');
L.push('# Syntropy component catalog');
L.push('');
L.push(
  'Every component in the Syntropy library, grouped by family and page: exact name, Figma id, level, library status, variant properties (values verbatim, typos included), other properties and a one-line description. Open it to confirm a name or a variant value before you write it down.'
);
L.push('');
L.push('> Generated by `scripts/build-catalog.mjs` from the component index and descriptions. Do not edit by hand; rerun the script.');
L.push('');
L.push(
  `Source: ${clean(index.source?.name)} (file \`${index.source?.file}\`), index updated ${index.source?.lastModified}. ` +
    `${index.counts?.pages} pages, ${comps.filter((c) => c.kind === 'set').length} component sets, ` +
    `${comps.filter((c) => c.kind === 'component').length} standalone components. ` +
    `Not in the published library: ${unpublishedSets} sets and ${unpublishedStandalone} standalone components (marked **no**).`
);
L.push('');
L.push('How to read a row:');
L.push('- **Library**: `yes` = in the published Syntropy library; **no** = exists only inside the Syntropy file (see `unpublished.md`).');
L.push('- **Level**: atom, molecule or organism (from the descriptions). Compose upward; never rebuild a lower level inline.');
L.push('- **Variant properties**: Figma property name and its values exactly as Figma spells them. Copy them verbatim.');
L.push('- **Other properties**: booleans, text and instance swaps by Figma name. Code names are in `references/data/components-index.json` (`canonical`).');
L.push('- Names flagged *duplicate name* exist twice: always cite the id.');
L.push('');

for (const fam of index.families) {
  const famKey = `${fam.code} ${fam.name}`;
  const pages = index.pages.filter((p) => p.family === famKey);
  if (!pages.length) continue;
  L.push(`## ${famKey}`);
  L.push('');
  for (const page of pages) {
    const items = comps.filter((c) => c.page === page.slug);
    const ref = hasReferenceImage(page.slug)
      ? `reference image \`references/data/examples/${page.slug}/reference.png\``
      : 'no reference image (use the Figma screenshot route in `images.md`)';
    L.push(`### ${page.code} ${clean(page.name)}`);
    L.push('');
    L.push(
      `Page status: ${page.status}${page.status !== 'stable' ? ' (not stable: do not use for new production work)' : ''} · guide \`references/data/components/${page.slug}.md\` · ${ref}`
    );
    L.push('');
    L.push('| Component | Id | Level | Library | Variant properties | Other properties | Description |');
    L.push('| --- | --- | --- | --- | --- | --- | --- |');
    for (const c of items) {
      const d = descriptions[c.id] || {};
      const flags = [];
      if (c.kind === 'component') flags.push('standalone');
      if (c.status !== 'stable') flags.push(`status ${c.status}`);
      if (c.hidden) flags.push('hidden, internal only');
      if (nameCount.get(c.name) > 1) flags.push('duplicate name');
      const name = `\`${clean(c.name)}\`${flags.length ? ` *(${flags.join(', ')})*` : ''}`;
      L.push(
        `| ${name} | ${c.id} | ${d.level || ''} | ${c.published ? 'yes' : '**no**'} | ${variantSummary(c.props) || ''} | ${otherProps(c.props)} | ${oneLine(d.description || c.description || '')} |`
      );
    }
    L.push('');
  }
}

L.push('## A to Z');
L.push('');
L.push('Every component name with its page code and id.');
L.push('');
const sorted = [...comps].sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }) || a.id.localeCompare(b.id));
for (const c of sorted) {
  L.push(`- \`${clean(c.name)}\` · ${c.pageCode} · ${c.id}${c.published ? '' : ' · not published'}${c.status !== 'stable' ? ` · ${c.status}` : ''}`);
}
L.push('');
L.push('## Sources');
L.push('');
L.push(`- Component index: ${indexPath.startsWith(skillRoot) ? 'references/data/components-index.json' : 'knowledge/components/index.json'} (Figma file ${index.source?.file})`);
L.push(`- Descriptions: ${descPath && descPath.startsWith(skillRoot) ? 'references/data/components-descriptions.json' : 'knowledge/components/descriptions.json'}`);
L.push('');

const out = L.join('\n');
if (/\u2014/.test(out)) {
  console.error('em dash found in generated catalog');
  process.exit(1);
}
if (checkOnly) {
  const current = existsSync(outPath) ? await readFile(outPath, 'utf8') : '';
  if (current !== out) {
    console.error(`${outPath} is out of date; run node scripts/build-catalog.mjs`);
    process.exit(1);
  }
  console.log('catalog up to date');
} else {
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, out);
  console.log(`wrote ${outPath}: ${out.split('\n').length} lines, ${comps.length} components`);
}
